"""Run RAGAS evaluation metrics against the work-intel RAG pipeline."""
import argparse
import json
import os
import subprocess
import sys
from datetime import datetime, timezone

WORK_INTEL_HOME = os.environ.get("WORK_INTEL_HOME", os.path.expanduser("~/.work-intel"))
SCRIPTS_DIR = os.path.dirname(os.path.abspath(__file__))
DEFAULT_MODEL = "jinaai/jina-embeddings-v5-text-small"
REGRESSION_THRESHOLD = 0.05

# Allow `from _llm_judge import ...` when invoked as a standalone script.
if SCRIPTS_DIR not in sys.path:
    sys.path.insert(0, SCRIPTS_DIR)
from _llm_judge import get_judge as build_llm  # noqa: E402


def load_config(config_path: str) -> dict:
    if not os.path.exists(config_path):
        return {}
    with open(config_path) as f:
        return json.load(f)


def retrieve_context(question: str, top_k: int = 5) -> list[str]:
    result = subprocess.run(
        [sys.executable, os.path.join(SCRIPTS_DIR, "query_chroma.py"),
         "--q", question, "--top-k", str(top_k), "--output", "json"],
        capture_output=True, text=True,
    )
    if result.returncode != 0 or not result.stdout.strip():
        return []
    items = json.loads(result.stdout)
    return [item.get("text", "") for item in items if item.get("text")]


def load_prior_report(reports_dir: str, current_path: str) -> dict | None:
    if not os.path.isdir(reports_dir):
        return None
    reports = sorted(
        [f for f in os.listdir(reports_dir) if f.startswith("ragas-report-") and f.endswith(".json")],
        reverse=True,
    )
    for r in reports:
        full = os.path.join(reports_dir, r)
        if full != current_path:
            with open(full) as f:
                return json.load(f)
    return None


def format_delta(current: float, prior: float | None) -> str:
    if prior is None:
        return "(no prior)"
    delta = current - prior
    sign = "+" if delta >= 0 else ""
    regressed = delta < -REGRESSION_THRESHOLD
    tag = " — REGRESSION" if regressed else ""
    icon = "⚠️" if regressed else "✅"
    return f"{icon} ({sign}{delta:.2f} vs prior{tag})"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--testset", default=os.path.join(WORK_INTEL_HOME, "ragas-testset.json"))
    parser.add_argument("--config", default=os.path.join(WORK_INTEL_HOME, "config.json"))
    parser.add_argument("--output", required=True)
    args = parser.parse_args()

    if not os.path.exists(args.testset):
        print(f"❌ Testset not found: {args.testset}", file=sys.stderr)
        print("   Run ragas_generate_testset.py first.", file=sys.stderr)
        sys.exit(1)

    with open(args.testset) as f:
        testset = json.load(f)

    # Filter out items that still have placeholder Q&A (not yet generated by agent)
    ready = [t for t in testset if not t.get("question", "").startswith("__GENERATE")]
    if not ready:
        print("❌ No ready Q&A pairs found. The evaluate-rag skill must generate questions first.", file=sys.stderr)
        sys.exit(1)

    cfg = load_config(args.config)

    try:
        from ragas import evaluate
        from ragas.metrics import (
            answer_relevancy,
            context_precision,
            context_recall,
            faithfulness,
        )
        from ragas.llms import LangchainLLMWrapper
        from datasets import Dataset
    except ImportError:
        print("❌ ragas or datasets not installed. Run: pip install ragas datasets", file=sys.stderr)
        sys.exit(1)

    llm, judge_label = build_llm(cfg)
    wrapped_llm = LangchainLLMWrapper(llm)

    rows: list[dict] = []
    for item in ready:
        contexts = retrieve_context(item["question"])
        if not contexts:
            contexts = item.get("ground_truth_contexts", [""])
        rows.append({
            "question": item["question"],
            "answer": item.get("ground_truth_answer", ""),
            "contexts": contexts,
            "ground_truth": item.get("ground_truth_answer", ""),
        })

    dataset = Dataset.from_list(rows)

    metrics = [context_precision, context_recall, faithfulness, answer_relevancy]
    for m in [faithfulness, answer_relevancy]:
        m.llm = wrapped_llm  # type: ignore[attr-defined]

    result = evaluate(dataset, metrics=metrics)
    # ragas 0.4.x: evaluate() returns EvaluationResult exposing .to_pandas();
    # pyright's stubs see it as Executor, hence the type: ignore. .to_dict() is
    # called on the resulting pandas Series — pyright narrows to float|int because
    # Series.mean() can return either, but at runtime we always have a Series here.
    scores = result.to_pandas().mean().to_dict()  # type: ignore[attr-defined]

    report = {
        "timestamp": datetime.now(timezone.utc).isoformat(),
        "judge": judge_label,
        "n_questions": len(rows),
        "metrics": {
            "context_precision": round(scores.get("context_precision", 0), 4),
            "context_recall": round(scores.get("context_recall", 0), 4),
            "faithfulness": round(scores.get("faithfulness", 0), 4),
            "answer_relevancy": round(scores.get("answer_relevancy", 0), 4),
        },
    }

    os.makedirs(os.path.dirname(os.path.abspath(args.output)), exist_ok=True)
    with open(args.output, "w") as f:
        json.dump(report, f, indent=2)

    prior = load_prior_report(os.path.dirname(args.output), args.output)
    prior_metrics = prior.get("metrics", {}) if prior else {}

    print(f"\nRAG Evaluation Report — {report['timestamp'][:10]}")
    print("=" * 50)
    m = report["metrics"]
    for key, label in [
        ("context_precision", "Context Precision"),
        ("context_recall",    "Context Recall"),
        ("faithfulness",      "Faithfulness"),
        ("answer_relevancy",  "Answer Relevancy"),
    ]:
        delta_str = format_delta(m[key], prior_metrics.get(key))
        print(f"{label:22s}: {m[key]:.2f}  {delta_str}")

    print(f"\nJudge: {judge_label}")
    print(f"Test set: {len(rows)} questions")
    print(f"Report saved: {args.output}")

    has_regression = any(
        m[k] - prior_metrics.get(k, m[k]) < -REGRESSION_THRESHOLD
        for k in m
        if k in prior_metrics
    )
    if has_regression:
        sys.exit(2)


if __name__ == "__main__":
    main()
